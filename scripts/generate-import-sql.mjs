// Turns the parsed form responses into an idempotent SQL import for the
// Supabase SQL editor. The editor runs as postgres, so the admin-only RLS
// policies from migration 001 don't block the write and no service-role key
// has to be copied onto disk.
//
// Usage: node scripts/generate-import-sql.mjs readings.json supabase/import_readings.sql
import { readFileSync, writeFileSync } from "node:fs";

const [, , IN = "readings.json", OUT = "supabase/import_readings.sql"] = process.argv;

const CLIENT_NAME = "Tarragon Place";
const PROPERTY_NAME = "Tarragon Place";

const rows = JSON.parse(readFileSync(IN, "utf-8"));
const q = (v) => (v === null || v === undefined ? "null" : "'" + String(v).replace(/'/g, "''") + "'");

const values = rows
  .map((r) => {
    const value = Number.parseFloat(r.raw_value);
    return `  (${q(r.captured_at)}::timestamptz, ${q(r.label)}, ${r.is_communal}, ${q(r.service)}, ${q(r.raw_value)}, ${value}, ${q(r.photo_url)})`;
  })
  .join(",\n");

const P = q(PROPERTY_NAME);
const C = q(CLIENT_NAME);
const DIGITS = "'^[0-9]+(\\.[0-9]+)?$'";

const sql = `-- ============================================================
-- Historical import: Tarragon Place meter readings, Feb-Aug 2026
-- ============================================================
-- Generated by scripts/generate-import-sql.mjs from the Google Form
-- responses export. Run in the Supabase SQL editor AFTER migration 005.
--
-- Source: "Form responses 1" tab, ${rows.length} readings across 7 months.
-- The monthly tabs are filtered views of that same tab and "Meter Comp" is
-- derived, so neither is imported.
--
-- SAFE TO RE-RUN. Every step is guarded:
--   * the client, property, units and meters are created only if absent
--   * a reading is skipped if that meter already has one in the same
--     calendar month, so re-running imports nothing twice and an existing
--     partial import (migration 002 mentions ~678 live readings) is topped
--     up rather than duplicated
--
-- Run import_preflight.sql FIRST and read its output. If it shows communal
-- meters under labels other than the ones below, rename them there before
-- running this, or you will get a second meter for the same physical one.
--
-- The SQL editor runs this as a single transaction: a failure anywhere
-- rolls the whole thing back. Do not add BEGIN/COMMIT and do not run it in
-- pieces. The verification block at the bottom prints what landed.

-- Plain temp tables, not ON COMMIT DROP: whether the SQL editor wraps the
-- script in one transaction or autocommits each statement, session-scoped
-- temp tables survive either way. Dropped up front so a re-run starts clean.

drop table if exists import_rows;
drop table if exists imported_ids;
drop table if exists target_property;

create temporary table import_rows (
  captured_at timestamptz not null,
  label text not null,
  is_communal boolean not null,
  service text not null,
  raw_value text not null,
  reading_value numeric not null,
  photo_url text
);

insert into import_rows
  (captured_at, label, is_communal, service, raw_value, reading_value, photo_url)
values
${values};

-- ------------------------------------------------------------
-- 1. Client + property
-- ------------------------------------------------------------

insert into clients (name)
select ${C}
where not exists (select 1 from clients where name = ${C});

insert into properties (name, address, client_id)
select ${P}, null, (select id from clients where name = ${C})
where not exists (select 1 from properties where name = ${P});

-- Adopt a property that predates the clients table.
update properties
set client_id = (select id from clients where name = ${C})
where name = ${P} and client_id is null;

-- Pin the target to ONE property id. Nothing stops two properties sharing a
-- name, and if that ever happened every join below would silently double.
create temporary table target_property as
select id from properties where name = ${P} order by created_at limit 1;

do $$
begin
  if (select count(*) from target_property) <> 1 then
    raise exception 'expected exactly one property named %, found %',
      ${P}, (select count(*) from properties where name = ${P});
  end if;
end $$;

-- ------------------------------------------------------------
-- 2. Units (numbered labels only; communal meters have no unit)
-- ------------------------------------------------------------

insert into units (property_id, unit_number)
select distinct (select id from target_property), i.label
from import_rows i
where i.is_communal = false
on conflict (property_id, unit_number) do nothing;

-- ------------------------------------------------------------
-- 3. Meters
-- ------------------------------------------------------------
-- One per label+service. A unit meter is matched through its unit, so an
-- existing meter is reused whatever its label says; a communal meter is
-- matched on label, because that is all it has.
--
-- Label convention follows what the app actually renders:
--   * unit meters keep migration 002's "101 - Water" form. The label is only
--     shown on the Meters admin screen; report.ts and the review queue
--     resolve a unit meter through units.unit_number instead.
--   * communal meters get the bare name ("Main Water Meter"), because for
--     those the label IS the display name everywhere — report.ts falls back
--     to it when unit_id is null, and the capture list prints it raw.

insert into meters (property_id, unit_id, service, label, is_communal)
select distinct t.id, u.id, i.service, i.label || ' - ' || initcap(i.service), false
from import_rows i
cross join target_property t
join units u on u.property_id = t.id and u.unit_number = i.label
where i.is_communal = false
  and not exists (
    select 1 from meters m
    where m.unit_id = u.id and m.service = i.service and m.retired_at is null
  );

insert into meters (property_id, unit_id, service, label, is_communal)
select distinct t.id, null::uuid, i.service, i.label, true
from import_rows i
cross join target_property t
where i.is_communal = true
  and not exists (
    select 1 from meters m
    where m.property_id = t.id and m.label = i.label
      and m.service = i.service and m.retired_at is null
  );

-- ------------------------------------------------------------
-- 4. Readings
-- ------------------------------------------------------------
-- captured_by stays null: these were captured on paper by the reader, not
-- by a signed-in admin. flag_status is set to 'ok' here and recomputed in
-- step 5, once every row is in place to compare against.
--
-- unit_id and service are the legacy columns migration 002 deliberately
-- kept; service is still NOT NULL, so both are populated from the meter.

create temporary table imported_ids (id uuid primary key, raw_value text not null);

-- RETURNING inside a data-modifying CTE hands back exactly the rows this
-- statement wrote, so step 5 re-flags only those and never touches history
-- an admin has already reviewed. (meter_id, captured_at) is unique within
-- "fresh" — the parser keeps one reading per meter per month — so joining
-- the returned rows back to it cannot fan out.

with resolved as (
  select i.*, m.id as meter_id, m.unit_id as meter_unit_id
  from import_rows i
  cross join target_property t
  join meters m
    on m.property_id = t.id
   and m.service = i.service
   and m.retired_at is null
   and (
     (i.is_communal = false and m.unit_id = (
       select u.id from units u where u.property_id = t.id and u.unit_number = i.label
     ))
     or (i.is_communal = true and m.unit_id is null and m.label = i.label)
   )
),
fresh as (
  select r.* from resolved r
  where not exists (
    select 1 from meter_readings mr
    where mr.meter_id = r.meter_id
      and date_trunc('month', mr.captured_at) = date_trunc('month', r.captured_at)
  )
),
ins as (
  insert into meter_readings
    (meter_id, unit_id, service, reading_value, photo_url, notes, flag_status, captured_at)
  select f.meter_id, f.meter_unit_id, f.service, f.reading_value, f.photo_url,
         null::text, 'ok', f.captured_at
  from fresh f
  returning id, meter_id, captured_at
)
insert into imported_ids (id, raw_value)
select ins.id, f.raw_value
from ins
join fresh f on f.meter_id = ins.meter_id and f.captured_at = ins.captured_at;

-- ------------------------------------------------------------
-- 5. Flagging
-- ------------------------------------------------------------
-- Mirrors src/lib/flagging.ts exactly, in the same precedence order, and
-- compares against the whole table so pre-existing readings count as history.

-- 5a. possible_partial: the raw entry is not plain digits with one optional
--     decimal point ("20188.09e", "7192.133m3", "280891 0").
update meter_readings mr
set flag_status = 'possible_partial'
from imported_ids ii
where ii.id = mr.id
  and ii.raw_value !~ ${DIGITS};

-- 5b. below_prev: lower than this meter's own preceding reading.
--     The lookup sits in a CTE rather than a LATERAL in the UPDATE's FROM
--     list, because a LATERAL cannot reference the UPDATE target table.
with prev as (
  select
    mr.id,
    (
      select p.reading_value
      from meter_readings p
      where p.meter_id = mr.meter_id and p.captured_at < mr.captured_at
      order by p.captured_at desc
      limit 1
    ) as prev_value
  from meter_readings mr
  join imported_ids ii on ii.id = mr.id
)
update meter_readings mr
set flag_status = 'below_prev'
from prev
where prev.id = mr.id
  and mr.flag_status = 'ok'
  and prev.prev_value is not null
  and mr.reading_value < prev.prev_value;

-- 5c. above_2x_avg: more than twice the mean of the 50 most recent readings
--     from OTHER meters of the same service on this property, up to this
--     row's timestamp.
--
--     KNOWN DEFECT, carried over deliberately: this compares absolute
--     cumulative dial values, not consumption deltas, so a meter with a
--     naturally larger dial trips every month. src/lib/flagging.ts documents
--     it; the import reproduces app behaviour rather than quietly diverging.
with sib as (
  select
    mr.id,
    (
      select avg(x.reading_value)
      from (
        select o.reading_value
        from meter_readings o
        join meters om on om.id = o.meter_id
        where om.property_id = m.property_id
          and om.service = m.service
          and o.meter_id <> mr.meter_id
          and o.captured_at <= mr.captured_at
        order by o.captured_at desc
        limit 50
      ) x
    ) as mean
  from meter_readings mr
  join imported_ids ii on ii.id = mr.id
  join meters m on m.id = mr.meter_id
)
update meter_readings mr
set flag_status = 'above_2x_avg'
from sib
where sib.id = mr.id
  and mr.flag_status = 'ok'
  and sib.mean > 0
  and mr.reading_value > sib.mean * 2;

-- ------------------------------------------------------------
-- Verification
-- ------------------------------------------------------------

select 'inserted this run' as report, count(*) from imported_ids;

select 'readings by month' as report, to_char(mr.captured_at, 'YYYY-MM') as month, count(*)
from meter_readings mr
join meters m on m.id = mr.meter_id
join target_property t on t.id = m.property_id
group by 2 order by 2;

select 'meters' as report, m.service, m.is_communal, count(*)
from meters m
join target_property t on t.id = m.property_id
group by 2, 3 order by 2, 3;

select 'flags on imported rows' as report, mr.flag_status, count(*)
from meter_readings mr
join imported_ids ii on ii.id = mr.id
group by 2 order by 3 desc;
`;

writeFileSync(OUT, sql);
console.log(`wrote ${OUT} (${rows.length} readings, ${(sql.length / 1024).toFixed(0)} KB)`);
